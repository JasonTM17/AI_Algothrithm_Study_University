def resolve_language(language: str | None) -> str:
    """Return a known language key, tolerating legacy mojibake labels from old sessions."""
    if language == ENGLISH:
        return ENGLISH
    if language == VIETNAMESE or language in LEGACY_VIETNAMESE_KEYS:
        return VIETNAMESE
    if language and ENGLISH in language:
        return ENGLISH
    return VIETNAMESE


def translate(language: str | None, key: str, **kwargs) -> str:
    locale = LOC.get(resolve_language(language), LOC[VIETNAMESE])
    text = locale.get(key, LOC[ENGLISH].get(key, key))
    return text.format(**kwargs) if kwargs else text
